def main():
    # Read existing TSV
    if not TSV_PATH.exists():
        print(f"Error: {TSV_PATH} not found")
        sys.exit(1)
    
    with open(TSV_PATH, 'r', encoding='utf-8') as f:
        reader = csv.DictReader(f, delimiter='\t')
        for row in reader:
            if row['lang'] == 'en':
                existing_en_lemmas.add(row['lemma'].lower())
                existing_en_fun_ids.add(row['fun_id'])
                existing_en_pairs.add((row['lemma'].lower(), row['pos']))
    
    # Combine all groups
    all_groups = [G1, G2, G3, G4, G5, G6, G7, G8, G9, G10, G11, G12, G13, G14, G15, G16, G17, G18, G19, G20, G21, G22, G23, G24, G25, G26, G27, G28, G29, G30]
    
    # Filter out duplicates
    for group in all_groups:
        for fun_id, lemma, pos in group:
            lemma_lower = lemma.lower()
            if lemma_lower in existing_en_lemmas:
                continue
            if fun_id in existing_en_fun_ids:
                continue
            if (lemma_lower, pos) in existing_en_pairs:
                continue
            new_entries.append((fun_id, lemma, pos))
    
    print(f"Existing EN lemmas: {len(existing_en_lemmas)}")
    print(f"Existing EN fun_ids: {len(existing_en_fun_ids)}")
    print(f"New EN entries to add: {len(new_entries)}")
    print(f"Projected EN lemmas after expansion: {len(existing_en_lemmas) + len(new_entries)}")
    
    if len(new_entries) == 0:
        print("No new entries to add")
        return
    
    # Append new entries to TSV
    with open(TSV_PATH, 'a', encoding='utf-8') as f:
        for fun_id, lemma, pos in new_entries:
            # Create minimal EN entry (case forms empty for now, will be filled by generation)
            # For nouns, we need at least nominative
            if pos == 'noun':
                line = f"{fun_id}\t{lemma}\ten\t{pos}\t{lemma}\t\t\t\t\t\t\t\t\t\t\t\t\t\t\n"
            elif pos == 'verb':
                line = f"{fun_id}\t{lemma}\ten\t{pos}\t\t\t\t\t\t\t\t\t\t{lemma}\t\t\t\t\t\t\n"
            elif pos == 'adjective':
                line = f"{fun_id}\t{lemma}\ten\t{pos}\t{lemma}\t\t\t\t\t\t\t\t\t\t\t\t\t\t\n"
            elif pos == 'adverb':
                line = f"{fun_id}\t{lemma}\ten\t{pos}\t{lemma}\t\t\t\t\t\t\t\t\t\t\t\t\t\t\n"
            elif pos == 'conjunction':
                line = f"{fun_id}\t{lemma}\ten\t{pos}\t{lemma}\t\t\t\t\t\t\t\t\t\t\t\t\t\t\n"
            else:
                line = f"{fun_id}\t{lemma}\ten\t{pos}\t{lemma}\t\t\t\t\t\t\t\t\t\t\t\t\t\t\n"
            f.write(line)
    
    print(f"Appended {len(new_entries)} new EN entries to {TSV_PATH}")

if __name__ == "__main__":
    main()
