def load_paradigms() -> dict:
    if PARADIGMS_PATH.exists():
        with open(PARADIGMS_PATH, 'r', encoding='utf-8') as f:
            return json.load(f)
    return {}


def save_paradigms(data: dict):
    with open(PARADIGMS_PATH, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)


def verb_paradigm(lemma: str) -> dict | None:
    parses = morph.parse(lemma)
    if not parses:
        return None
    p = None
    for cand in parses:
        if 'VERB' in cand.tag or 'INFN' in cand.tag:
            p = cand
            break
    if p is None:
        return None

    # Determine aspect
    aspect = 'impf'
    if 'perf' in p.tag:
        aspect = 'perf'
    elif 'impf' in p.tag:
        aspect = 'impf'

    # Determine transitivity
    trans = 'intr'
    if 'tran' in p.tag:
        trans = 'tran'
    elif 'intr' in p.tag:
        trans = 'intr'

    forms = {}
    # Infinitive
    inf = p.inflect({'INFN'})
    forms['Inf'] = inf.word if inf else lemma

    # Past
    past_masc = p.inflect({'past', 'masc'})
    past_fem = p.inflect({'past', 'femn'})
    past_neut = p.inflect({'past', 'neut'})
    past_pl = p.inflect({'past', 'plur'})
    forms['PastSgMasc'] = past_masc.word if past_masc else (inf.word if inf else lemma)
    forms['PastSgFem'] = past_fem.word if past_fem else (inf.word if inf else lemma)
    forms['PastSgNeut'] = past_neut.word if past_neut else (inf.word if inf else lemma)
    forms['PastPl'] = past_pl.word if past_pl else (inf.word if inf else lemma)

    # Present / Future
    pres_tense = 'pres' if aspect == 'impf' else 'futr'
    for person, number, key in [
        (1, 'sing', 'Pres1Sg' if aspect == 'impf' else 'Fut1Sg'),
        (2, 'sing', 'Pres2Sg' if aspect == 'impf' else 'Fut2Sg'),
        (3, 'sing', 'Pres3Sg' if aspect == 'impf' else 'Fut3Sg'),
        (1, 'plur', 'Pres1Pl' if aspect == 'impf' else 'Fut1Pl'),
        (2, 'plur', 'Pres2Pl' if aspect == 'impf' else 'Fut2Pl'),
        (3, 'plur', 'Pres3Pl' if aspect == 'impf' else 'Fut3Pl'),
    ]:
        form = p.inflect({pres_tense, f"{person}per", number})
        forms[key] = form.word if form else f"[{lemma}:{key}]"

    # Imperative
    imp_sg = p.inflect({'impr', 'sing'})
    imp_pl = p.inflect({'impr', 'plur'})
    forms['ImpSg'] = imp_sg.word if imp_sg else f"[{lemma}:ImpSg]"
    forms['ImpPl'] = imp_pl.word if imp_pl else f"[{lemma}:ImpPl]"

    return {
        "pos": "Verb",
        "aspect": aspect,
        "transitivity": trans,
        "forms": forms
    }


def adj_paradigm(lemma: str) -> dict | None:
    parses = morph.parse(lemma)
    if not parses:
        return None
    p = None
    for cand in parses:
        if 'ADJF' in cand.tag:
            p = cand
            break
    if p is None:
        return None

    forms = {}
    cases = ['nomn', 'gent', 'datv', 'accs', 'ablt', 'loct']
    numbers = ['sing', 'plur']
    genders = ['masc', 'femn', 'neut']

    # Full forms
    for case in cases:
        for number in numbers:
            if number == 'sing':
                for gender in genders:
                    form = p.inflect({case, number, gender})
                    key = f"{case_key(case)}{number.capitalize()[:1]}{gender.capitalize()[:1]}"
                    # Actually file uses: NomSgMasc, GenSgFem, etc.
                    key = f"{case_key(case)}{number[:1].upper()}{number[1:].lower()}{gender.capitalize()}"
                    forms[key] = form.word if form else f"[{lemma}:{key}]"
            else:
                form = p.inflect({case, number})
                key = f"{case_key(case)}Pl"
                forms[key] = form.word if form else f"[{lemma}:{key}]"

    # Short forms (ADJS)
    for gender in genders:
        # Try to get short form via ADJS tag or by inflecting
        short_parses = morph.parse(lemma)
        short_form = None
        for sp in short_parses:
            if 'ADJS' in sp.tag:
                sf = sp.inflect({gender})
                if sf:
                    short_form = sf.word
                    break
        if not short_form:
            # Try inflecting original as short
            sf = p.inflect({gender, 'ADJS'})
            short_form = sf.word if sf else ""
        forms[f"Short{gender.capitalize()}"] = short_form if short_form else ""

    return {
        "pos": "Adj",
        "forms": forms
    }


def case_key(case: str) -> str:
    return {
        'nomn': 'Nom', 'gent': 'Gen', 'datv': 'Dat',
        'accs': 'Acc', 'ablt': 'Ins', 'loct': 'Loc'
    }[case]


def main():
    paradigms = load_paradigms()
    existing = set(paradigms.keys())
    added_v = 0; added_a = 0; skipped = 0; errors = 0

    for lemma in VERBS:
        if lemma in existing:
            skipped += 1
            continue
        para = verb_paradigm(lemma)
        if para is None:
            errors += 1
            print(f"WARN: cannot parse verb {lemma}")
            continue
        paradigms[lemma] = para
        added_v += 1
        existing.add(lemma)

    for lemma in ADJS:
        if lemma in existing:
            skipped += 1
            continue
        para = adj_paradigm(lemma)
        if para is None:
            errors += 1
            print(f"WARN: cannot parse adjective {lemma}")
            continue
        paradigms[lemma] = para
        added_a += 1
        existing.add(lemma)

    save_paradigms(paradigms)

    print(f"Report: verbs_added={added_v}, adjs_added={added_a}, skipped={skipped}, errors={errors}")
    print(f"Total Verb entries: {sum(1 for v in paradigms.values() if v.get('pos')=='Verb')}")
    print(f"Total Adj entries:  {sum(1 for v in paradigms.values() if v.get('pos')=='Adj')}")


if __name__ == "__main__":
    main()
