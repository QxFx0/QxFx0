def extract_words(sql_text: str) -> set:
    words = set()
    for line in sql_text.splitlines():
        m = re.search(r",\s*'(.+?)'\s*\)\s*;?\s*$", line)
        if not m:
            continue
        text = m.group(1).replace("''", "'")
        for w in re.findall(r'[А-ЯЁа-яё]{3,}', text):
            w_low = w.lower()
            if w_low in STOP_WORDS:
                continue
            words.add(w_low)
    return words


def noun_paradigm(lemma: str) -> dict | None:
    parses = morph.parse(lemma)
    if not parses:
        return None
    p = None
    for cand in parses:
        if 'NOUN' in cand.tag:
            p = cand
            break
    if p is None:
        return None

    gender = str(p.tag.gender) if p.tag.gender else None
    animacy = str(p.tag.animacy) if p.tag.animacy else None

    # pymorphy3 gender values: masc, femn, neut
    if gender not in ('masc', 'femn', 'neut'):
        # fallback
        if lemma.endswith('а') or lemma.endswith('я'):
            gender = 'femn'
        elif lemma.endswith('о') or lemma.endswith('е'):
            gender = 'neut'
        else:
            gender = 'masc'

    if animacy not in ('anim', 'inan'):
        # Heuristic: people/animals are animate; most others inanimate
        animacy = 'inan'

    cases = ['nomn', 'gent', 'datv', 'accs', 'ablt', 'loct']
    numbers = ['sing', 'plur']
    forms = {}
    for num in numbers:
        for case in cases:
            form = p.inflect({case, num})
            if form:
                key = case_key(case, num)
                forms[key] = form.word
    if len(forms) < 6:
        return None

    # Ensure all 12 keys exist; fill with lemma + suffix if missing
    for num in numbers:
        for case in cases:
            key = case_key(case, num)
            if key not in forms:
                forms[key] = lemma

    return {
        "pos": "Noun",
        "gender": gender.capitalize() if gender else "Masc",
        "animacy": "Anim" if animacy == 'anim' else "Inan",
        "forms": forms
    }


def case_key(case: str, number: str) -> str:
    case_map = {
        'nomn': 'Nom', 'gent': 'Gen', 'datv': 'Dat',
        'accs': 'Acc', 'ablt': 'Ins', 'loct': 'Loc'
    }
    num_map = {'sing': 'Sg', 'plur': 'Pl'}
    return f"{case_map[case]}{num_map[number]}"


def load_paradigms() -> dict:
    if PARADIGMS_PATH.exists():
        with open(PARADIGMS_PATH, 'r', encoding='utf-8') as f:
            return json.load(f)
    return {}


def save_paradigms(data: dict):
    with open(PARADIGMS_PATH, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)


