def main():
    paradigms = load_paradigms()
    existing = set(paradigms.keys())

    with open(SEED_SQL_PATH, 'r', encoding='utf-8') as f:
        sql = f.read()

    words = extract_words(sql)
    # Also add explicit nouns
    words.update(NOUNS_EXTRA)
    added = 0
    skipped = 0
    errors = 0

    for w in sorted(words):
        if w in existing:
            skipped += 1
            continue
        para = noun_paradigm(w)
        if para is None:
            errors += 1
            continue
        paradigms[w] = para
        added += 1
        existing.add(w)

    save_paradigms(paradigms)

    print(f"Report: added={added}, skipped={skipped}, errors={errors}")
    print(f"Total Noun entries: {sum(1 for v in paradigms.values() if v.get('pos') == 'Noun')}")


if __name__ == "__main__":
    main()
