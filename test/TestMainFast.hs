  -- 'defaultSalienceWeights' / 'defaultFieldHeuristics' CAFs and verifies
  -- they load tuned config files when present.
main :: IO ()
main = do
  suiteTest <- selectSuites "QXFX0_FAST_SUITE" fastSuites
  testCounts <- runTestTT suiteTest

  if errors testCounts + failures testCounts > 0
    then exitFailure
    else exitSuccess

