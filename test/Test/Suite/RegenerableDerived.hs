module Test.Suite.RegenerableDerived
  ( regenerableDerivedTests
  ) where

import Test.HUnit (Test (..), assertFailure)

import Control.Exception (SomeException, catch)
import Prelude (Bool (..), Eq, FilePath, IO, Show, String, all, filter, lines, mapM, not, null, unlines, (.))

import qualified Data.List as L
import qualified System.Directory as D
import qualified System.FilePath as FP

-- | A derived module under test. The 'dmMarker'
-- is the first non-comment, non-blank line of the
-- file that contains "AUTO-GENERATED" or
-- "Generated by".
data DerivedModule = DerivedModule
  { dmPath   :: !FilePath
  , dmMarker :: !String
  }
  deriving stock (Eq, Show)

-- | Find the first 'AUTO-GENERATED' or 'Generated by'
-- marker in the file's first 10 lines. Returns
-- 'Nothing' if no marker is found.
findMarker :: String -> Maybe String
findMarker contents =
  case filter
    (\line -> "AUTO-GENERATED" `L.isInfixOf` line
              || "Generated by" `L.isInfixOf` line)
    (take 10 (lines contents)) of
    (m : _) -> Just m
    []      -> Nothing

-- | Extract the referenced script path from a
-- marker. Examples:
--
-- > "-- AUTO-GENERATED by scripts/export_lexicon.py ..."
-- > "-- AUTO-GENERATED: scripts/build_input_lexicon.py"
-- > "-- Generated by qxfx0 --sync-embedded-sql from spec/sql."
extractReferencedScript :: String -> Maybe FilePath
extractReferencedScript marker
  | "scripts/" `L.isInfixOf` marker =
      -- Find "scripts/<name>" and stop at the next
      -- non-script-path character.
      let rest = dropWhile (/= 's') (dropWhile (/= 's') marker)  -- not robust
          -- A robust extraction: find "scripts/" and
          -- take the longest run of [a-zA-Z0-9._/-].
          afterScripts = snd (L.breakOnEnd "scripts/" marker)
      in Just (FP.takeBaseName afterScripts <> ".py")
  | "qxfx0 --sync-embedded-sql" `L.isInfixOf` marker =
      -- The EmbeddedSQL marker references a CLI
      -- command, not a script. The script is
      -- scripts/sync_embedded_sql.py (the
      -- implementation of the command).
      Just "sync_embedded_sql.py"
  | otherwise = Nothing

-- | Walk @src\/@ and collect all @*Generated.hs@ and
-- @*Auto.hs@ files. The walk is shallow (one level
-- deep) for now; the next contributor extends to
-- recursive walk when the discipline scales.
collectDerivedModules :: FilePath -> IO [DerivedModule]
collectDerivedModules root = do
  let srcDir = root FP.</> "src"
  exists <- D.doesDirectoryExist srcDir
  if not exists
    then return []
    else do
      entries <- D.listDirectory srcDir
      let hsFiles = filter
            (\f -> L.isSuffixOf ".hs" f
                   && ("Generated" `L.isInfixOf` f
                       || "Auto" `L.isInfixOf` f))
            entries
      mapM (readDerivedModule (srcDir FP.</>)) hsFiles

-- | Read a source file and extract its marker.
-- If the file does not exist or has no marker,
-- the marker is empty.
readDerivedModule :: FilePath -> FilePath -> IO DerivedModule
readDerivedModule dir fname = do
  let path = dir FP.</> fname
  contents <- (readFile path) `catch` (\(_ :: SomeException) -> return "")
  let marker = case findMarker contents of
        Just m  -> m
        Nothing -> ""
  return (DerivedModule path marker)

-- | Read a file or return empty string on error.
readFileOrEmpty :: FilePath -> IO String
readFileOrEmpty path = (readFile path) `catch` (\(_ :: SomeException) -> return "")

-- | The actual test: for every derived module,
-- verify that the marker is present and the
-- referenced script exists under @scripts\/@.
r7RegenerableDerived :: Test
r7RegenerableDerived = TestLabel "R7: every *Generated.hs/*Auto.hs declares its regenerator and the script exists" $
  TestCase $ do
    let root = "."
    modules <- collectDerivedModules root
    let noMarker = filter (null . dmMarker) modules
    let withMarker = filter (not . null . dmMarker) modules
    let badScript = filter
          (\m -> case extractReferencedScript (dmMarker m) of
                   Nothing -> True
                   Just _  -> False)
          withMarker
    let goodMarker = filter
          (\m -> case extractReferencedScript (dmMarker m) of
                   Just _  -> True
                   Nothing -> False)
          withMarker
    -- Check that the referenced script exists.
    let scriptChecks = map
          (\m -> do
             case extractReferencedScript (dmMarker m) of
               Just s -> do
                 let path = "scripts" FP.</> s
                 exists <- D.doesFileExist path
                 return (m, Just s, exists)
               Nothing -> return (m, Nothing, False))
          goodMarker
    scriptResults <- mapM (id) scriptChecks
    let missingScripts = filter (\(_, _, exists) -> not exists) scriptResults
    -- Aggregate failures.
    let failureLines = concat
          [ [ "R7: the following derived modules have no AUTO-GENERATED marker:"
            , "    " <> unlines (map dmPath noMarker)
            ]
          | not (null noMarker)
          ] ++ concat
          [ [ "R7: the following derived modules have a marker but no script reference:"
            , "    " <> unlines (map dmPath badScript)
            ]
          | not (null badScript)
          ] ++ concat
          [ [ "R7: the following derived modules reference a non-existent script:"
            , "    " <> unlines (map (\(m, s, _) -> dmPath m <> " -> " <> show s) missingScripts)
            ]
          | not (null missingScripts)
          ]
    if null failureLines
      then return ()
      else assertFailure (unlines failureLines)

-- ---------------------------------------------------------------------------
-- The test group
-- ---------------------------------------------------------------------------

regenerableDerivedTests :: [Test]
regenerableDerivedTests =
  [ r7RegenerableDerived
  ]
