{-|
Module      : Test.Suite.RegenerableDerived
Description : R7 red-row closure (ENFORCEMENT_MATRIX.md §1).

The closure plan's ADR-0013 §3 Rule 7 says: "Derived
modules must remain regenerable." The rule has two
parts:

  * every derived module (file name matching
    @*Generated.hs@ or @*Auto.hs@) must declare its
    generator in a top-of-file marker;
  * the generator script must exist under @scripts/@
    (the source of truth for the regeneration).

The static companion is @scripts/check_architecture.sh@
rule [16] (heuristic check). The dynamic companion is
'Test.Suite.RenderAuthorityStub' for the F-11 case
(Lexicon.Generated is a render-input, not an
authority-bearing module). What was missing is a
**HUnit regression lock** for the discipline.

This test suite is the **runtime** companion of
@check_architecture.sh@ [16] and
@scripts/check_generated_artifacts.sh@. The three
checks together close the **red row** for R7 in
@docs\/closure\/ENFORCEMENT_MATRIX.md@ §1.

== Why this is a regression lock, not a generator

A full R7 check would run the generator, compare its
output to the checked-in artifact, and fail on drift.
That requires Python, GF, and (potentially) Agda in
the test environment. The discipline of R7 is "must
remain regenerable"; a generator-drift check enforces
that.

The current test is a **discipline lock**: it
verifies the *invariant* that a derived module
declares its generator and the generator exists.
A separate generator-drift test is added when the
test environment stabilises (see @FOLLOWUPS.md@
future sections).

== Coverage

The test scans @src\/@ for files matching
@*Generated.hs@ and @*Auto.hs@. For each, it
extracts the @AUTO-GENERATED@ marker (or
"@Generated by qxfx0 --sync-embedded-sql@"
for the EmbeddedSQL case) and verifies:

  1. the marker is present;
  2. the marker references a file under
     @scripts\/@;
  3. the referenced script exists.

The test fails on the first violation and lists
all violations in the failure message.
