data ParadigmEntry = ParadigmEntry
  { pePos     :: !Text
  , peGender  :: !(Maybe Text)
  , peAnimacy :: !(Maybe Text)
  , peAspect  :: !(Maybe Text)
  , peTransitivity :: !(Maybe Text)
  , peForms   :: !(Map Text Text)
  } deriving stock (Eq, Show, Generic)
    deriving anyclass (NFData)

instance FromJSON ParadigmEntry where
  parseJSON = genericParseJSON defaultOptions
    { fieldLabelModifier = \lbl -> case lbl of
        ('p':'e':rest) -> map toLower rest
        _              -> map toLower lbl
    }

data RuntimeParadigms = RuntimeParadigms
  { rpMap        :: !(Map Text ParadigmEntry)
  , rpExceptions :: !(Map Text ParadigmEntry)
  } deriving stock (Eq, Show)

--------------------------------------------------------------------------------
-- Load
--------------------------------------------------------------------------------

loadRuntimeParadigms :: BS.ByteString -> Either String RuntimeParadigms
loadRuntimeParadigms bs = do
  paradigms <- eitherDecodeStrict bs
  pure RuntimeParadigms { rpMap = paradigms, rpExceptions = mempty }

emptyRuntimeParadigms :: RuntimeParadigms
emptyRuntimeParadigms = RuntimeParadigms mempty mempty

-- | Test helper: loaded paradigms for test suites. Not for production use.
testRuntimeParadigms :: RuntimeParadigms
testRuntimeParadigms = unsafePerformIO loadDefaultRuntimeParadigms
{-# NOINLINE testRuntimeParadigms #-}

-- | Load paradigms + exceptions from default paths. Pure IO — no global cache.
loadDefaultRuntimeParadigms :: IO RuntimeParadigms
loadDefaultRuntimeParadigms = do
  paradigms <- loadFile "resources/morphology/paradigms.json" "paradigms"
  exceptions <- loadFile "resources/morphology/exceptions.json" "exceptions"
  pure RuntimeParadigms { rpMap = paradigms, rpExceptions = exceptions }
  where
    loadFile path label = do
      exists <- doesFileExist path
      if not exists
        then do
          hPutStrLn stderr $ "[RuntimeParadigms] " <> label <> " file not found: " <> path
          pure mempty
        else do
          bs <- BS.readFile path
          case eitherDecodeStrict bs of
            Left err -> do
              hPutStrLn stderr $ "[RuntimeParadigms] " <> label <> " parse error: " <> err
              pure mempty
            Right mp -> pure (mp :: Map Text ParadigmEntry)

