hasParadigm :: RuntimeParadigms -> Text -> Bool
hasParadigm rp lemma = M.member lemma (rpMap rp) || M.member lemma (rpExceptions rp)

allParadigmLemmas :: RuntimeParadigms -> [Text]
allParadigmLemmas rp = M.keys (rpMap rp) ++ M.keys (rpExceptions rp)

-- | Guess grammatical gender using the runtime paradigms database,
-- falling back to suffix heuristics when the lemma is absent.
guessGender :: RuntimeParadigms -> Text -> Maybe Gender
guessGender rp t =
  case lemmaGender rp t of
    Just "femn" -> Just Femn
    Just "neut" -> Just Neut
    Just _      -> Just Masc
    Nothing     ->
      let w = T.toLower t
      in if T.isSuffixOf "а" w || T.isSuffixOf "я" w
           then Just Femn
         else if T.isSuffixOf "о" w || T.isSuffixOf "е" w
           then Just Neut
         else Just Masc

-- | Like 'guessGender' but returns a default instead of 'Nothing'.
guessGenderOr :: RuntimeParadigms -> Gender -> Text -> Gender
guessGenderOr rp def t =
  case lemmaGender rp t of
    Just "femn" -> Femn
    Just "neut" -> Neut
    Just _      -> Masc
    Nothing     ->
      let w = T.toLower t
      in if T.isSuffixOf "а" w || T.isSuffixOf "я" w
           then Femn
         else if T.isSuffixOf "о" w || T.isSuffixOf "е" w
           then Neut
         else def

inferGenitive :: RuntimeParadigms -> Text -> Number -> Maybe Text
inferGenitive rp lemma = inferNounForm rp lemma Gen

inferPrepositional :: RuntimeParadigms -> Text -> Number -> Maybe Text
inferPrepositional rp lemma = inferNounForm rp lemma Loc

inferAccusative :: RuntimeParadigms -> Text -> Number -> Maybe Text
inferAccusative rp lemma = inferNounForm rp lemma Acc

inferInstrumental :: RuntimeParadigms -> Text -> Number -> Maybe Text
inferInstrumental rp lemma = inferNounForm rp lemma Ins

inferDative :: RuntimeParadigms -> Text -> Number -> Maybe Text
inferDative rp lemma = inferNounForm rp lemma Dat

inferNounForm :: RuntimeParadigms -> Text -> NounCase -> Number -> Maybe Text
inferNounForm rp lemma targetCase number =
  let w = T.unpack (T.toLower lemma)
      g = guessGender rp lemma
      animacy = peAnimacy <$> M.lookup lemma (rpMap rp)
  in case (g, w) of
       (_, [])   -> Nothing
       (_, [_])  -> Nothing
       (Just Masc, cs) -> inferMasc cs animacy
       (Just Femn, cs) -> inferFemn cs
       (Just Neut, cs) -> inferNeut cs
       (_, _)     -> Nothing
     where
       safeLast cs = if null cs then Nothing else Just (cs !! (length cs - 1))
       safeInit cs = if null cs then [] else take (length cs - 1) cs
       safeLastEq cs c = case safeLast cs of Just c' -> c' == c; Nothing -> False
       isConsStem cs = not (null cs) &&
                       case safeLast cs of
                         Just l  -> l `notElem` ("аеёиоуыэюяьй" :: String)
                         Nothing -> False
       afterVelarOrSibilant s = case safeLast s of
         Just c  -> c `elem` ("кгхжшчщ" :: String)
         Nothing -> False
       decl base (sgG,sgD,sgA_anim,sgA_inan,sgI,sgL) (plG,plD,plA_anim,plA_inan,plI,plL) =
         let animacyLocal = case M.lookup lemma (rpMap rp) of
               Just entry -> peAnimacy entry
               Nothing    -> Nothing
             (sgA, plA) = case animacyLocal of
               Just "anim" -> (sgA_anim, plA_anim)
               Just "inan" -> (sgA_inan, plA_inan)
               _           -> (sgA_inan, plA_inan)  -- default to inanimate
         in case (number, targetCase) of
           (Sg, Gen) -> Just $ T.pack base <> T.pack sgG
           (Sg, Dat) -> Just $ T.pack base <> T.pack sgD
           (Sg, Acc) -> Just $ T.pack base <> T.pack sgA
           (Sg, Ins) -> Just $ T.pack base <> T.pack sgI
           (Sg, Loc) -> Just $ T.pack base <> T.pack sgL
           (Pl, Gen) -> Just $ T.pack base <> T.pack plG
           (Pl, Dat) -> Just $ T.pack base <> T.pack plD
           (Pl, Acc) -> Just $ T.pack base <> T.pack plA
           (Pl, Ins) -> Just $ T.pack base <> T.pack plI
           (Pl, Loc) -> Just $ T.pack base <> T.pack plL
           _         -> Nothing
       inferMasc cs mAnim
         | isConsStem cs =
             let plNom = if afterVelarOrSibilant cs then cs <> "и" else cs <> "ы"
                 plGen = if afterVelarOrSibilant cs then cs <> "ей" else cs <> "ов"
             in decl cs ("а","у","а",cs,"ом","е") (plGen,"ам",plGen,plNom,"ами","ах")
         | safeLastEq cs 'й' =
             let b = safeInit cs
             in decl b ("я","ю","я",cs,"ем","е") ("ев","ям","ев",b<>"и","ями","ях")
         | safeLastEq cs 'ь' =
             let b = safeInit cs
             in decl b ("я","ю","я",cs,"ём","и") ("ей","ям","ей",b<>"и","ями","ях")
         | otherwise = Nothing
       inferFemn cs
         | safeLastEq cs 'а' =
             let b = safeInit cs
                 yOrI = if afterVelarOrSibilant b then "и" else "ы"
             in case (number, targetCase) of
                  (Sg, Gen) -> Just $ T.pack b <> T.pack yOrI
                  (Sg, Dat) -> Just $ T.pack b <> "е"
                  (Sg, Acc) -> Just $ T.pack b <> "у"
                  (Sg, Ins) -> Just $ T.pack b <> "ой"
                  (Sg, Loc) -> Just $ T.pack b <> "е"
                  _         -> Nothing
         | safeLastEq cs 'я' =
             let b = safeInit cs
             in case (number, targetCase) of
                  (Sg, Gen) -> Just $ T.pack b <> "и"
                  (Sg, Dat) -> Just $ T.pack b <> "е"
                  (Sg, Acc) -> Just $ T.pack b <> "ю"
                  (Sg, Ins) -> Just $ T.pack b <> "ей"
                  (Sg, Loc) -> Just $ T.pack b <> "е"
                  _         -> Nothing
         | safeLastEq cs 'ь' =
             let b = safeInit cs
             in case (number, targetCase) of
                  (Sg, Gen) -> Just $ T.pack b <> "и"
                  (Sg, Dat) -> Just $ T.pack b <> "и"
                  (Sg, Acc) -> Just $ T.pack b <> "ь"
                  (Sg, Ins) -> Just $ T.pack b <> "ью"
                  (Sg, Loc) -> Just $ T.pack b <> "и"
                  _         -> Nothing
         | otherwise = Nothing
       inferNeut cs
         | safeLastEq cs 'о' =
             let b = safeInit cs
             in case (number, targetCase) of
                  (Sg, Gen) -> Just $ T.pack b <> "а"
                  (Sg, Dat) -> Just $ T.pack b <> "у"
                  (Sg, Acc) -> Just $ T.pack cs
                  (Sg, Ins) -> Just $ T.pack b <> "ом"
                  (Sg, Loc) -> Just $ T.pack b <> "е"
                  _         -> Nothing
         | safeLastEq cs 'е' =
             let b = safeInit cs
                 isIye = length cs >= 3 && cs !! (length cs - 2) == 'и'
             in if isIye
                then let ib = take (length cs - 2) cs
                     in case (number, targetCase) of
                          (Sg, Gen) -> Just $ T.pack ib <> "ия"
                          (Sg, Dat) -> Just $ T.pack ib <> "ию"
                          (Sg, Acc) -> Just $ T.pack cs
                          (Sg, Ins) -> Just $ T.pack ib <> "ием"
                          (Sg, Loc) -> Just $ T.pack ib <> "ии"
                          (Pl, Gen) -> Just $ T.pack ib <> "ий"
                          (Pl, Dat) -> Just $ T.pack ib <> "иям"
                          (Pl, Acc) -> Just $ T.pack ib <> "ия"
                          (Pl, Ins) -> Just $ T.pack ib <> "иями"
                          (Pl, Loc) -> Just $ T.pack ib <> "иях"
                          _         -> Nothing
                else case (number, targetCase) of
                       (Sg, Gen) -> Just $ T.pack b <> "я"
                       (Sg, Dat) -> Just $ T.pack b <> "ю"
                       (Sg, Acc) -> Just $ T.pack cs
                       (Sg, Ins) -> Just $ T.pack b <> "ем"
                       (Sg, Loc) -> Just $ T.pack b <> "е"
                       _         -> Nothing
         | otherwise = Nothing

